    sobrante = np.maximum(0, df_pred - df_real)
    # Rotura
    rotura = np.maximum(0, df_real - df_pred)

    # Pesos de penalización 'h' y 'p'
    coste_holding = (sobrante * h).sum().sum()
    coste_shortage = (rotura * p).sum().sum()

    return coste_holding + coste_shortage

