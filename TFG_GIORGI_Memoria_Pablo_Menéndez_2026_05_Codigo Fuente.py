# BÚSQUEDA DE HIPERPARÁMETROS (GRID SEARCH) CON AUTO-LSTM

import pandas as pd
from neuralforecast import NeuralForecast
from neuralforecast.auto import AutoLSTM
from neuralforecast.losses.pytorch import DistributionLoss
from ray import tune

train_nixtla = train.copy().astype(float)
test_real_nf = test_real.copy().astype(float)

train_nixtla.index.name = 'ds'
df_train_long = train_nixtla.reset_index().melt(id_vars='ds', var_name='unique_id', value_name='y')
df_train_long['ds'] = pd.to_datetime(df_train_long['ds'])

# DEFINIR EL ESPACIO DE BÚSQUEDA (Grid Search)
lstm_config = {
    # Lags a probar: 15 semanas, 26 semanas y 52 semanas
    "input_size": tune.choice([15, 26, 52]),

    # Capas de la red a probar: 1, 2 o 3
    "encoder_n_layers": tune.choice([1, 2, 3]),

    "encoder_hidden_size": tune.choice([128, 256, 512]),
    "learning_rate": tune.loguniform(1e-4, 1e-2),

    # Parámetros fijos
    "max_steps": 1000,
    "scaler_type": 'robust'
}

# AUTO-LSTM
modelo_auto_lstm = AutoLSTM(
    h=1,
    loss=DistributionLoss(distribution='NegativeBinomial'),
    config=lstm_config,
    num_samples=10,
    search_alg="random"
)

# ENTRENAR
nf_auto = NeuralForecast(models=[modelo_auto_lstm], freq="W-MON")
nf_auto.fit(df=df_train_long)

